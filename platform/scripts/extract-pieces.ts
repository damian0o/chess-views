/**
 * One-off: extract the cburnett piece images (CC BY-SA 3.0, Colin M.L. Burnett, as embedded in
 * chessground 9.2.1) from the proof of concept's pieces.css into src/app/board/pieces.ts.
 * Run: npx tsx scripts/extract-pieces.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';

const css = readFileSync(new URL('../../pieces.css', import.meta.url), 'utf8');
const out: Record<string, string> = {};
for (const m of css.matchAll(/\.piece\.([wb][PNBRQK])\s*\{\s*background-image:\s*url\('([^']+)'\)/g)) out[m[1]!] = m[2]!;
if (Object.keys(out).length !== 12) throw new Error(`expected 12 pieces, found ${Object.keys(out).length}`);
writeFileSync(new URL('../src/app/board/pieces.ts', import.meta.url),
  `// Generated by scripts/extract-pieces.ts — the cburnett set by Colin M.L. Burnett, CC BY-SA 3.0\n// (as embedded in chessground 9.2.1, https://github.com/lichess-org/chessground). Do not edit.\n` +
  `export const PIECES: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`);
console.log('pieces:', Object.keys(out).join(' '));
