import sys
from playwright.sync_api import sync_playwright
BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8080/"
res = []
def chk(n, ok, d=""): res.append((n, ok, d))
with sync_playwright() as p:
    b = p.chromium.launch()
    d = b.new_context(viewport={"width": 1200, "height": 900})
    pg = d.new_page(); errs = []; pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(BASE, wait_until="networkidle"); pg.wait_for_timeout(400)
    pg.click("#open-library"); pg.wait_for_timeout(300)
    n = pg.evaluate("document.querySelectorAll('.libitem').length")
    total = len(pg.request.get(BASE + "positions.json").json()["positions"])
    chk(f"library shows all {total} entries", n == total, f"n={n}")
    thumbs = pg.evaluate("document.querySelectorAll('.libitem .thumb i.piece').length")
    chk("thumbnails have pieces", thumbs > 200, f"pieces={thumbs}")
    pg.fill("#libsearch", "mate"); pg.wait_for_timeout(200)
    n2 = pg.evaluate("document.querySelectorAll('.libitem').length")
    chk("search 'mate' narrows the list", 0 < n2 < total, f"n={n2}")
    pg.fill("#libsearch", ""); pg.click("#libtags button:has-text('endgame')"); pg.wait_for_timeout(200)
    n3 = pg.evaluate("document.querySelectorAll('.libitem').length")
    chk("tag 'endgame' filters", n3 == 6, f"n={n3}")
    pg.click("#libtags button:has-text('endgame')"); pg.wait_for_timeout(100)
    pg.click(".libitem:has-text('Knight fork')"); pg.wait_for_timeout(400)
    closed = not pg.evaluate("document.getElementById('library').open")
    tab = pg.evaluate("__viewer.state.tab"); fen = pg.evaluate("__viewer.state.chess.fen()")
    chk("opening an entry closes dialog, switches view, loads fen", closed and tab == "knight" and fen.startswith("2r1k3/8/8/8/4N3"), f"closed={closed} tab={tab} fen={fen}")
    chk("hash carries the fen and view", "view=knight" in pg.url and "fen=" in pg.url, pg.url)
    # every entry loads without a page error and the status line fills in
    bad = []
    for i in range(total):
        pg.click("#open-library"); pg.wait_for_timeout(150)
        name = pg.evaluate(f"document.querySelectorAll('.libitem')[{i}].querySelector('.name').textContent")
        pg.evaluate(f"document.querySelectorAll('.libitem')[{i}].click()"); pg.wait_for_timeout(250)
        turn = pg.inner_text("#turn"); sq = pg.evaluate("document.querySelectorAll('.board .sq, .dcell').length")
        if errs or not any(k in turn for k in ("to move", "Checkmate", "Stalemate")) or sq < 64: bad.append((name, turn, sq, list(errs))); errs.clear()
    chk(f"all {total} entries open cleanly in their view", not bad, str(bad))
    pg.click("#open-library"); pg.wait_for_timeout(150); pg.click(".libitem:has-text('Opera')"); pg.wait_for_timeout(300)
    ply = pg.evaluate("__viewer.state.ply"); mv = pg.evaluate("__viewer.state.moves.length")
    chk("Opera game opens at ply 23 of 33 with the player bar", ply == 23 and mv == 33 and pg.evaluate("document.getElementById('nav').classList.contains('on')"), f"ply={ply} moves={mv}")
    pg.close()
    pg = d.new_page(); pg.goto(BASE + "#pos=lucena", wait_until="networkidle"); pg.wait_for_timeout(600)
    chk("#pos=lucena link opens the entry", pg.evaluate("__viewer.state.chess.fen()").startswith("1K1k4/1P6") and pg.evaluate("__viewer.state.tab") == "roads")
    pg.close()
    m = b.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2, is_mobile=True, has_touch=True)
    pg = m.new_page(); pg.goto(BASE, wait_until="networkidle"); pg.wait_for_timeout(300)
    chk("mobile: no overflow with the extra button", pg.evaluate("document.documentElement.scrollWidth") == 390)
    pg.click("#open-library"); pg.wait_for_timeout(300)
    b.close()
for n, ok, dd in res: print(("PASS " if ok else "FAIL ") + n + ("" if ok else "  -> " + dd))
print("ALL PASS" if all(r[1] for r in res) else "SOME FAILED")
